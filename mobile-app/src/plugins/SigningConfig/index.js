/**
 * SigningConfig - an Expo config plugin for FrogPaper Mobile.
 *
 * Copy to: mobile-app/src/plugins/SigningConfig/index.js
 * Then add ""./src/plugins/SigningConfig"" to the `plugins` array in mobile-app/app.json.
 *
 * WHY THIS EXISTS
 * ---------------
 * `expo prebuild` regenerates android/ from scratch, and the generated
 * app/build.gradle signs the release build with `signingConfigs.debug` unless
 * something rewrites it. That is how v1.12.0 shipped an APK signed with the
 * throwaway debug key: BUILD SUCCESSFUL, wrong signature, would not install over
 * an existing FrogPaper install.
 *
 * Because prebuild runs on every CI build, the fix has to live in a config
 * plugin - the same way ./src/plugins/WallpaperManagerFix survives prebuild.
 * This plugin points the release build at keystore.properties, which the CI
 * workflow writes from repository secrets before Gradle starts.
 *
 * The workflow still verifies the finished APK with apksigner and refuses to
 * publish anything not signed by CN=FrogPaper. This plugin just makes the
 * happy path the only path.
 */

const { withAppBuildGradle } = require('@expo/config-plugins');

const START = '// @frogpaper-signing-start';
const END = '// @frogpaper-signing-end';

const SIGNING_CONFIG = `${START}
        release {
            def frogpaperPropsFile = rootProject.file('keystore.properties')
            if (frogpaperPropsFile.exists()) {
                def frogpaperProps = new Properties()
                frogpaperPropsFile.withInputStream { frogpaperProps.load(it) }
                storeFile rootProject.file(frogpaperProps['storeFile'])
                storePassword frogpaperProps['storePassword']
                keyAlias frogpaperProps['keyAlias']
                keyPassword frogpaperProps['keyPassword']
            }
        }
        ${END}`;

/**
 * Adds a `release` signingConfig and switches the release build type onto it.
 * Pure string work so it can be unit-tested without an Android toolchain.
 *
 * @param {string} contents app/build.gradle as generated by expo prebuild
 * @returns {string} patched contents (unchanged if already patched or unexpected)
 */
function applySigningConfig(contents) {
  if (typeof contents !== 'string' || contents.length === 0) return contents;
  if (contents.includes(START)) return contents; // idempotent: prebuild + re-run

  let out = contents;
  let patchedSigningConfigs = false;

  // 1. Put the release signingConfig inside the existing signingConfigs block.
  const signingConfigsMatch = out.match(/signingConfigs\s*\{/);
  if (signingConfigsMatch) {
    const at = signingConfigsMatch.index + signingConfigsMatch[0].length;
    out = out.slice(0, at) + '\n' + SIGNING_CONFIG + '\n' + out.slice(at);
    patchedSigningConfigs = true;
  } else {
    // No signingConfigs block at all (rare, but possible in future templates):
    // create one just before buildTypes.
    const buildTypesAt = out.search(/buildTypes\s*\{/);
    if (buildTypesAt === -1) return contents; // template we do not recognise
    const block = `    signingConfigs {\n${SIGNING_CONFIG}\n    }\n\n    `;
    out = out.slice(0, buildTypesAt) + block + out.slice(buildTypesAt);
    patchedSigningConfigs = true;
  }

  // 2. Point the release build type at it instead of the debug key.
  const buildTypesAt = out.search(/buildTypes\s*\{/);
  if (buildTypesAt === -1) return contents;
  const head = out.slice(0, buildTypesAt);
  const tail = out.slice(buildTypesAt);

  // Work inside the release block only: the debug block legitimately uses the
  // debug key, and rewriting that one would break `assembleDebug`.
  const releaseMatch = tail.match(/release\s*\{/);
  if (!releaseMatch) return contents;
  const releaseAt = releaseMatch.index + releaseMatch[0].length;
  const beforeRelease = tail.slice(0, releaseAt);
  let releaseBlock = tail.slice(releaseAt);

  if (/signingConfig\s+signingConfigs\.debug/.test(releaseBlock)) {
    // Comment the debug line out so the diff is obvious to anyone reading the
    // generated file, then point it at the release key.
    releaseBlock = releaseBlock.replace(
      /([ \t]*)(signingConfig\s+signingConfigs\.debug)/,
      '$1// $2  (replaced by the SigningConfig config plugin)\n$1signingConfig signingConfigs.release'
    );
  } else if (!/signingConfig\s+signingConfigs\.release/.test(releaseBlock)) {
    releaseBlock = '\n            signingConfig signingConfigs.release' + releaseBlock;
  }
  out = head + beforeRelease + releaseBlock;

  if (!patchedSigningConfigs) return contents;
  return out;
}

module.exports = function withSigningConfig(config) {
  return withAppBuildGradle(config, (cfg) => {
    // Only the Groovy build script is handled; Kotlin DSL (build.gradle.kts)
    // would need a different patch, and Expo's template is Groovy today.
    if (cfg.modResults.language === 'groovy') {
      cfg.modResults.contents = applySigningConfig(cfg.modResults.contents);
    }
    return cfg;
  });
};

module.exports.applySigningConfig = applySigningConfig;
