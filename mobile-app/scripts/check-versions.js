#!/usr/bin/env node
/**
 * check-versions.js - the version numbers must agree.
 *
 * Three places carry a version:
 *   - app.json            what the app reads at runtime (Settings > About, via
 *                         expo-constants) and what EAS stamps on the APK;
 *   - package.json        what npm and the repo's own tooling report;
 *   - android/app/build.gradle  the native project, when one exists.
 *
 * app.json and package.json always have to match. The Gradle file only exists
 * after `expo prebuild` / in a native checkout, so when android/ is missing this
 * suite says so and checks the two that do exist instead of crashing (it used to
 * throw ENOENT on a plain clone, which made it useless in CI).
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PASS = '\x1b[32m[PASS]\x1b[0m';
const FAIL = '\x1b[31m[FAIL]\x1b[0m';

let passes = 0;
let failures = 0;

function check(name, condition, detail) {
  if (condition) {
    passes += 1;
    console.log(`${PASS} ${name}`);
  } else {
    failures += 1;
    console.log(`${FAIL} ${name}${detail ? ` -> ${detail}` : ''}`);
  }
}

function main() {
  console.log('versions');
  const appJson = JSON.parse(fs.readFileSync(path.join(ROOT, 'app.json'), 'utf8'));
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
  const expo = appJson.expo || {};

  check('app.json has a version', typeof expo.version === 'string' && expo.version.length > 0, String(expo.version));
  check('the version looks like x.y.z', /^\d+\.\d+\.\d+$/.test(expo.version), String(expo.version));
  check('package.json has a version', typeof pkg.version === 'string' && pkg.version.length > 0, String(pkg.version));
  check(
    'app.json and package.json agree',
    expo.version === pkg.version,
    `app.json=${expo.version} package.json=${pkg.version}`
  );
  check(
    'app.json has a versionCode',
    Number.isInteger(expo.android && expo.android.versionCode),
    String(expo.android && expo.android.versionCode)
  );

  const gradlePath = path.join(ROOT, 'android/app/build.gradle');
  if (!fs.existsSync(gradlePath)) {
    // Not a failure: the native project is generated by `expo prebuild`.
    console.log('SKIP android/app/build.gradle not present (run `expo prebuild` for the native checks)');
  } else {
    const gradle = fs.readFileSync(gradlePath, 'utf8');
    const gradleName = (gradle.match(/versionName\s+"([^"]+)"/) || [])[1];
    const gradleCode = (gradle.match(/versionCode\s+(\d+)/) || [])[1];
    check('build.gradle has a version name', !!gradleName, String(gradleName));
    check('app.json and build.gradle agree', expo.version === gradleName, `app.json=${expo.version} gradle=${gradleName}`);
    check(
      'app.json and build.gradle version codes agree',
      String(expo.android && expo.android.versionCode) === String(gradleCode),
      `app.json=${expo.android && expo.android.versionCode} gradle=${gradleCode}`
    );
  }

  console.log(`\n${passes} passed, ${failures} failed`);
  process.exit(failures === 0 ? 0 : 1);
}

main();
